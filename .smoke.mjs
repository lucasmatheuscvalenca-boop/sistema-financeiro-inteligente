import { chromium } from "@playwright/test";
const SP = process.argv[2];
const base = "http://localhost:3100";
const browser = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium" });
const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
page.on("pageerror", (e) => console.log("PAGEERROR", e.message));
page.on("console", (m) => { if (m.type() === "error") console.log("CONSOLE", m.text().slice(0, 300)); });
const email = `smoke${Date.now()}@exemplo.com`;
await page.goto(`${base}/criar-conta`);
await page.fill("input[name=name]", "Lucas");
await page.fill("input[name=email]", email);
await page.fill("input[name=password]", "senha-segura-123");
await page.check("input[name=consent]");
await page.click("button[type=submit]");
await page.waitForURL(/onboarding/, { timeout: 30000 });
await page.screenshot({ path: `${SP}/s1-welcome.png` });
await page.click("text=Começar");
await page.waitForURL(/etapa=mascot/, { timeout: 30000 });
await page.click("[data-testid=mascote-lince]");
await page.screenshot({ path: `${SP}/s2-mascot.png`, fullPage: true });
await page.click("button:has-text('Confirmar escolha')");
await page.waitForURL(/etapa=personal/, { timeout: 30000 });
await page.screenshot({ path: `${SP}/s3-personal.png`, fullPage: true });
await page.fill("input[name=birthYear]", "1994");
await page.selectOption("select[name=employmentStatus]", "clt");
await page.click("button:has-text('Salvar e continuar')");
await page.waitForURL(/etapa=financial/, { timeout: 30000 });
await page.fill("input[name=monthlyNetIncome]", "8.000,00");
await page.fill("input[name=essentialExpenses]", "4.000,00");
await page.fill("input[name=variableExpenses]", "2.000,00");
await page.selectOption("select[name=hasDebts]", "nao");
await page.fill("input[name=currentReserve]", "6.000,00");
await page.click("button:has-text('Salvar e continuar')");
await page.waitForURL(/etapa=life/, { timeout: 30000 });
await page.fill("textarea[name=shortTermGoals]", "Viajar para o Chile em março");
await page.click("button:has-text('Salvar e continuar')");
await page.waitForURL(/etapa=diagnosis/, { timeout: 30000 });
await page.screenshot({ path: `${SP}/s4-diagnosis.png`, fullPage: true });
await page.click("button:has-text('Ir para meu painel')");
await page.waitForURL(/painel/, { timeout: 30000 });
await page.screenshot({ path: `${SP}/s5-painel.png`, fullPage: true });
console.log("OK", email);
await browser.close();
